%% ========================== 辅助函数 ==========================
function value = be_i32(bytes)
unsignedValue = bitor( ...
    bitor(bitshift(uint32(bytes(1)), 24), bitshift(uint32(bytes(2)), 16)), ...
    bitor(bitshift(uint32(bytes(3)), 8), uint32(bytes(4))));
value = double(typecast(unsignedValue, "int32"));
end

function value = be_i16(bytes)
unsignedValue = bitor(bitshift(uint16(bytes(1)), 8), uint16(bytes(2)));
value = double(typecast(unsignedValue, "int16"));
end

function scaledValue = apply_scalar(value, scalar)
scaledValue = value;
if scalar > 0
    scaledValue = value * scalar;
elseif scalar < 0
    scaledValue = value / abs(scalar);
end
end

function amplitude = ibm32_to_single(words)
signValue = ones(size(words));
signValue(bitget(words, 32) ~= 0) = -1;
exponent = double(bitand(bitshift(words, -24), uint32(127))) - 64;
fraction = double(bitand(words, uint32(hex2dec("00FFFFFF")))) / 2^24;

amplitude = single(signValue .* fraction .* 16 .^ exponent);
amplitude(words == 0) = 0;
end

function percentileValue = amplitude_percentile(amplitude, percentile)
stride = max(1, floor(numel(amplitude) / 2e6));
sampledAmplitude = abs(double(amplitude(1:stride:end)));
sampledAmplitude = sort(sampledAmplitude(isfinite(sampledAmplitude)));
index = max(1, round(percentile / 100 * numel(sampledAmplitude)));
percentileValue = max(sampledAmplitude(index), eps);
end

function colorMap = seismic_colormap(numberOfColors)
anchorPosition = [0, 0.18, 0.36, 0.50, 0.64, 0.78, 0.90, 1.00];
anchorColor = [ ...
    0.0000, 0.0000, 0.0000
    0.2500, 0.2500, 0.2500
    0.6902, 0.6902, 0.6902
    0.9412, 0.9412, 0.8784
    0.9412, 0.9412, 0.2510
    0.9412, 0.6902, 0.0000
    0.9412, 0.1882, 0.0000
    0.9412, 0.0000, 0.0000];

colorMap = interp1( ...
    anchorPosition, anchorColor, linspace(0, 1, numberOfColors), "linear");
end
