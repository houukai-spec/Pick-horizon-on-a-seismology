%% PSDM SEG-Y 剖面显示与点击查询
% 修改“用户设置”后，直接运行本脚本。
% 在剖面上单击，可查看最近样点对应的深度、CMP 及关键道头信息。
clear;
clc;

%% ========================== 用户设置 ==========================
inputSegyPath = "F:\修论\Data\AZN16\kM2107Pr_009_PreSDM_Final_5-30_Deg_Full_Stack_With_AGC_TVD_AZN16-1010.sgy";
outputPngPath = "";   % 设为 "" 时不输出 PNG

cmpMinimum = -Inf;                    % 读取的最小 CMP；-Inf 表示不限制
cmpMaximum = Inf;                     % 读取的最大 CMP； Inf 表示不限制

traceStep  = 1;                       % 1=读取范围内每一道；2=每隔一道读取
sampleStep = 1;                       % 1=读取每个样点；2=每隔一个样点读取

depthSampleM = 2.0;                   % 原始垂向采样间隔，单位 m
firstDepthM  = 0.0;                   % 第一个样点的 TVD 深度，单位 m
xAxisType    = "cmp";                 % "distance"、"cmp" 或 "trace"

clipPercentile = 99;                  % 振幅显示裁剪百分位
polarity       = 1;                   % 设为 -1 时反转极性
pngResolution  = 300;                 % PNG 输出分辨率，单位 dpi
colorMapSize   = 256;                 % 色标级数
%% =============================================================

options = struct( ...
    "TraceStep", traceStep, ...
    "SampleStep", sampleStep, ...
    "CmpMinimum", cmpMinimum, ...
    "CmpMaximum", cmpMaximum, ...
    "DepthSampleM", depthSampleM, ...
    "FirstDepthM", firstDepthM, ...
    "XAxisType", xAxisType, ...
    "ClipPercentile", clipPercentile, ...
    "Polarity", polarity, ...
    "OutputPngPath", outputPngPath, ...
    "PngResolution", pngResolution, ...
    "ColorMapSize", colorMapSize);

section = read_and_plot_psdm(inputSegyPath, options);

%% ======================== 读取与显示 ==========================
function section = read_and_plot_psdm(filename, options)
fid = fopen(filename, "r", "ieee-be");
fileCloser = onCleanup(@() fclose(fid));

[sampleIntervalHeader, samplesPerTrace] = read_binary_header(fid);
traceBytes = 240 + samplesPerTrace * 4;

fseek(fid, 0, "eof");
fileBytes = ftell(fid);
traceCount = floor((fileBytes - 3600) / traceBytes);

allCmp = read_all_cmp(fid, traceCount, traceBytes);
traceIndex = find(allCmp >= options.CmpMinimum & allCmp <= options.CmpMaximum);
traceIndex = traceIndex(1:options.TraceStep:end);
sampleIndex = 1:options.SampleStep:samplesPerTrace;

[amplitude, header] = read_selected_traces( ...
    fid, traceIndex, sampleIndex, samplesPerTrace, traceBytes, options.Polarity);

depthM = options.FirstDepthM + (sampleIndex - 1) * options.DepthSampleM;
[xPlot, xLabelText] = make_horizontal_axis(options.XAxisType, traceIndex, header);
clipAmplitude = amplitude_percentile(amplitude, options.ClipPercentile);

[fig, ax, imageHandle, infoText] = create_section_figure( ...
    filename, xPlot, depthM, amplitude, clipAmplitude, ...
    xLabelText, options.ColorMapSize);

clickData = struct( ...
    "XPlot", xPlot, ...
    "DepthM", depthM, ...
    "Amplitude", amplitude, ...
    "TraceIndex", traceIndex, ...
    "Header", header, ...
    "Axes", ax, ...
    "InfoText", infoText);
imageHandle.ButtonDownFcn = @(~, ~) show_clicked_header(clickData);

if strlength(options.OutputPngPath) > 0
    exportgraphics(ax, options.OutputPngPath, "Resolution", options.PngResolution);
end

section = struct( ...
    "amplitude", amplitude, ...
    "depth_m", depthM, ...
    "trace_index", traceIndex, ...
    "header", header, ...
    "sample_interval_header_raw", sampleIntervalHeader, ...
    "depth_sample_m", options.DepthSampleM, ...
    "samples_per_trace", samplesPerTrace, ...
    "trace_count", traceCount, ...
    "clip_amplitude", clipAmplitude, ...
    "figure", fig, ...
    "axes", ax);

clear fileCloser;
end

function [sampleIntervalHeader, samplesPerTrace] = read_binary_header(fid)
fseek(fid, 3200 + 16, "bof");
sampleIntervalHeader = fread(fid, 1, "uint16=>double");

fseek(fid, 3200 + 20, "bof");
samplesPerTrace = fread(fid, 1, "uint16=>double");
end

function cmp = read_all_cmp(fid, traceCount, traceBytes)
cmp = zeros(1, traceCount);

for traceNumber = 1:traceCount
    traceStart = 3600 + (traceNumber - 1) * traceBytes;
    fseek(fid, traceStart + 20, "bof");
    cmp(traceNumber) = fread(fid, 1, "int32=>double");
end
end

function [amplitude, header] = read_selected_traces( ...
        fid, traceIndex, sampleIndex, samplesPerTrace, traceBytes, polarity)

numberOfTraces = numel(traceIndex);
amplitude = zeros(numel(sampleIndex), numberOfTraces, "single");
header = initialize_header(numberOfTraces);

for column = 1:numberOfTraces
    traceNumber = traceIndex(column);
    traceStart = 3600 + (traceNumber - 1) * traceBytes;

    fseek(fid, traceStart, "bof");
    rawHeader = fread(fid, 240, "uint8=>uint8");
    header = parse_trace_header(header, column, rawHeader);

    ibmWords = fread(fid, samplesPerTrace, "uint32=>uint32");
    traceAmplitude = ibm32_to_single(ibmWords);
    amplitude(:, column) = polarity * traceAmplitude(sampleIndex);
end
end

function header = initialize_header(numberOfTraces)
fieldNames = [ ...
    "traceSequenceLine", "traceSequenceFile", "fieldRecord", ...
    "traceWithinField", "energySourcePoint", "cmp", "traceWithinCmp", ...
    "traceIdCode", "coordinateScalar", "sourceX", "sourceY", ...
    "groupX", "groupY", "coordinateUnits", "delayRecordingMs", ...
    "traceSamples", "traceSampleInterval", "cdpX", "cdpY", ...
    "inlineNumber", "crosslineNumber", "shotpointNumber"];

header = struct();
for fieldName = fieldNames
    header.(fieldName) = zeros(1, numberOfTraces);
end
end

function header = parse_trace_header(header, column, raw)
header.traceSequenceLine(column)   = be_i32(raw(1:4));
header.traceSequenceFile(column)   = be_i32(raw(5:8));
header.fieldRecord(column)         = be_i32(raw(9:12));
header.traceWithinField(column)    = be_i32(raw(13:16));
header.energySourcePoint(column)   = be_i32(raw(17:20));
header.cmp(column)                 = be_i32(raw(21:24));
header.traceWithinCmp(column)      = be_i32(raw(25:28));
header.traceIdCode(column)         = be_i16(raw(29:30));
header.coordinateScalar(column)    = be_i16(raw(71:72));

coordinateScalar = header.coordinateScalar(column);
header.sourceX(column) = apply_scalar(be_i32(raw(73:76)), coordinateScalar);
header.sourceY(column) = apply_scalar(be_i32(raw(77:80)), coordinateScalar);
header.groupX(column)  = apply_scalar(be_i32(raw(81:84)), coordinateScalar);
header.groupY(column)  = apply_scalar(be_i32(raw(85:88)), coordinateScalar);

header.coordinateUnits(column)     = be_i16(raw(89:90));
header.delayRecordingMs(column)    = be_i16(raw(109:110));
header.traceSamples(column)        = be_i16(raw(115:116));
header.traceSampleInterval(column) = be_i16(raw(117:118));
header.cdpX(column)                 = apply_scalar(be_i32(raw(181:184)), coordinateScalar);
header.cdpY(column)                 = apply_scalar(be_i32(raw(185:188)), coordinateScalar);
header.inlineNumber(column)         = be_i32(raw(189:192));
header.crosslineNumber(column)      = be_i32(raw(193:196));
header.shotpointNumber(column)      = be_i32(raw(197:200));
end

function [xPlot, xLabelText] = make_horizontal_axis(xAxisType, traceIndex, header)
switch lower(xAxisType)
    case "distance"
        xPlot = [0, cumsum(hypot(diff(header.cdpX), diff(header.cdpY)))] / 1000;
        xLabelText = "沿测线距离 (km)";
    case "cmp"
        xPlot = header.cmp;
        xLabelText = "CMP";
    case "trace"
        xPlot = traceIndex;
        xLabelText = "道号";
end
end

